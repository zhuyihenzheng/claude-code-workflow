#!/usr/bin/env python3
"""单向同步路径规则，仅用标准库；输入采用 paths: 块列表，输出 UTF-8 / LF。"""

import argparse
import json
from pathlib import Path
import re
import sys


DEFAULT_PROJECT = Path(__file__).resolve().parents[1] / 'templates/project'
GENERATED = '# Generated by sync_rules.py; edit .claude/rules/ instead.\n'


def render_rule(source):
    text = source.read_text(encoding='utf-8')
    if not text.startswith('---\n') or '\n---\n' not in text[4:]:
        raise ValueError(f'{source}: expected YAML frontmatter')
    header, body = text[4:].split('\n---\n', 1)
    paths = []
    seen_paths = False
    for line in header.splitlines():
        if not line.strip() or line.lstrip().startswith('#'):
            continue
        if line == 'paths:' and not seen_paths:
            seen_paths = True
            continue
        item = re.fullmatch(r'\s+-\s+(.+?)\s*', line)
        if not seen_paths or item is None:
            raise ValueError(f'{source}: only a paths: block list is supported')
        value = item.group(1)
        if value.startswith('"'):
            value = json.loads(value)
        elif value.startswith("'") and value.endswith("'"):
            value = value[1:-1].replace("''", "'")
        elif not re.fullmatch(r'[\w./*?{}!\[\],-]+', value):
            raise ValueError(f'{source}: quote the glob as a string: {value}')
        if not isinstance(value, str) or not value:
            raise ValueError(f'{source}: paths must contain nonempty strings')
        paths.append(value)
    if not paths:
        raise ValueError(f'{source}: paths must not be empty')
    globs = json.dumps(','.join(paths), ensure_ascii=False)
    return f'---\n{GENERATED}applyTo: {globs}\n---\n{body}'


def sync(project, check=False):
    rules = project / '.claude/rules'
    if not rules.is_dir():
        raise ValueError(f'{rules}: source rules directory does not exist')
    output = project / '.github/instructions'
    # 全部解析成功后才写入，避免不支持的 frontmatter 留下半套镜像。
    expected = {output / f'{source.stem}.instructions.md': render_rule(source)
                for source in sorted(rules.glob('*.md'))}
    changed = False
    for target, content in expected.items():
        if target.exists() and target.read_bytes() == content.encode('utf-8'):
            continue
        changed = True
        print(f'{"Out of sync" if check else "Updated"}: {target}')
        if not check:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(content.encode('utf-8'))
    # 仅清理带本脚本标记的过期镜像，保留目标项目自行维护的其他指令。
    for target in sorted(output.glob('*.instructions.md')):
        if target not in expected and target.read_text(encoding='utf-8').startswith('---\n' + GENERATED):
            changed = True
            print(f'{"Out of sync" if check else "Removed"}: {target}')
            if not check:
                target.unlink()
    return 1 if check and changed else 0


def main():
    # 重定向到管道时 Windows 可能使用本地编码，统一日志编码以支持中文路径。
    sys.stdout.reconfigure(encoding='utf-8')
    sys.stderr.reconfigure(encoding='utf-8')
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('project_root', nargs='?', type=Path, default=DEFAULT_PROJECT,
                        help='project root (default: templates/project next to scripts/)')
    parser.add_argument('--check', action='store_true', help='report drift without writing; exit 1 on drift')
    args = parser.parse_args()
    try:
        return sync(args.project_root, args.check)
    except (OSError, ValueError) as error:
        print(f'Error: {error}', file=sys.stderr)
        return 2


if __name__ == '__main__':
    sys.exit(main())
